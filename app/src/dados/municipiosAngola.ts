/** Todos os municípios oficiais conhecidos para a província (lista completa do catálogo). */
export function municipiosOficiaisAngola(provincia: string): string[] {
  const chave = resolverProvinciaCatalogo(provincia);
  const lista = MUNICIPIOS_POR_PROVINCIA[chave];
  if (!lista?.length) return [];
  return [...lista].sort((a, b) => a.localeCompare(b, "pt"));
}
